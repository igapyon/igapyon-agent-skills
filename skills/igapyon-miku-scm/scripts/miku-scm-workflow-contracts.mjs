#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  WORKFLOW_MANIFEST,
  WORKFLOW_MANIFEST_VERSION,
} from "./miku-scm-workflow-manifest.mjs";

export const WORKFLOW_CONTRACT_LOCK_VERSION = "miku-scm.workflow-contract-lock/v1";

const SCRIPT_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const SKILL_DIRECTORY = path.dirname(SCRIPT_DIRECTORY);
const LOCK_FILE = path.join(SCRIPT_DIRECTORY, "miku-scm-workflow-contract-lock.mjs");
const TABLE_FILE = path.join(SKILL_DIRECTORY, "references", "workflow-contracts.md");

export function canonicalContractText(value) {
  return String(value).replace(/\r\n?/g, "\n");
}

export function contractSha256(value) {
  return createHash("sha256").update(canonicalContractText(value)).digest("hex");
}

function canonicalPair(entry, runnerSha256, specSha256) {
  return JSON.stringify({
    contract_id: entry.contract_id,
    contract_version: entry.contract_version,
    runner_sha256: runnerSha256,
    spec_sha256: specSha256,
  });
}

function assertSafeBasename(value, label) {
  if (typeof value !== "string" || !/^[A-Za-z0-9._-]+$/.test(value)) {
    throw new Error(`${label} must be one safe basename`);
  }
}

export async function calculateWorkflowContracts() {
  const ids = new Set();
  const contracts = [];
  for (const entry of WORKFLOW_MANIFEST) {
    if (ids.has(entry.contract_id)) throw new Error(`Duplicate workflow contract ID: ${entry.contract_id}`);
    ids.add(entry.contract_id);
    if (entry.contract_id !== entry.id) {
      throw new Error(`Workflow and contract IDs must match: ${entry.id}`);
    }
    if (!Number.isSafeInteger(entry.contract_version) || entry.contract_version < 1) {
      throw new Error(`Invalid contract version: ${entry.id}`);
    }
    assertSafeBasename(entry.runner_entry, `${entry.id} runner_entry`);
    assertSafeBasename(entry.contract_spec, `${entry.id} contract_spec`);
    assertSafeBasename(entry.contract_test, `${entry.id} contract_test`);

    const runnerPath = path.join(SCRIPT_DIRECTORY, entry.runner_entry);
    const specPath = path.join(SKILL_DIRECTORY, "references", entry.contract_spec);
    const testPath = path.join(SKILL_DIRECTORY, "tests", entry.contract_test);
    const [runner, spec] = await Promise.all([
      readFile(runnerPath),
      readFile(specPath),
      readFile(testPath),
    ]);
    const runnerSha256 = contractSha256(runner);
    const specSha256 = contractSha256(spec);
    contracts.push(Object.freeze({
      workflow: entry.id,
      contract_id: entry.contract_id,
      contract_version: entry.contract_version,
      runner_entry: entry.runner_entry,
      contract_spec: entry.contract_spec,
      contract_test: entry.contract_test,
      runner_sha256: runnerSha256,
      spec_sha256: specSha256,
      pair_sha256: contractSha256(canonicalPair(entry, runnerSha256, specSha256)),
    }));
  }
  return contracts;
}

export function renderContractLock(contracts) {
  return `// Generated by miku-scm-workflow-contracts.mjs. Do not edit.\n`
    + `export const WORKFLOW_CONTRACT_LOCK_VERSION = ${JSON.stringify(WORKFLOW_CONTRACT_LOCK_VERSION)};\n`
    + `export const WORKFLOW_CONTRACT_LOCK = Object.freeze(${JSON.stringify(contracts, null, 2)}.map(Object.freeze));\n`
    + "export function workflowContractById() {\n"
    + "  return new Map(WORKFLOW_CONTRACT_LOCK.map((entry) => [entry.workflow, entry]));\n"
    + "}\n";
}

export function renderContractTable(contracts) {
  const rows = contracts.map((entry) => (
    `| \`${entry.workflow}\` | ${entry.contract_version} | \`${entry.runner_entry}\` | `
    + `\`${entry.contract_spec}\` | \`${entry.contract_test}\` | `
    + `\`${entry.runner_sha256}\` | \`${entry.spec_sha256}\` | \`${entry.pair_sha256}\` |`
  ));
  return [
    "# Workflow Contracts",
    "",
    "Generated by `scripts/miku-scm-workflow-contracts.mjs`. Do not edit by hand.",
    "Runtime routing reads the generated lock module, not the detailed Markdown specs.",
    "",
    `Manifest: \`${WORKFLOW_MANIFEST_VERSION}\``,
    `Lock: \`${WORKFLOW_CONTRACT_LOCK_VERSION}\``,
    "",
    "| Workflow contract | Version | Runner | Normative spec | Contract test | runner_sha256 | spec_sha256 | pair_sha256 |",
    "|---|---:|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

async function matches(file, expected) {
  try {
    return canonicalContractText(await readFile(file, "utf8")) === canonicalContractText(expected);
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

export async function updateWorkflowContracts({ check = false } = {}) {
  const contracts = await calculateWorkflowContracts();
  const lock = renderContractLock(contracts);
  const table = renderContractTable(contracts);
  if (check) {
    const [lockMatches, tableMatches] = await Promise.all([
      matches(LOCK_FILE, lock),
      matches(TABLE_FILE, table),
    ]);
    if (!lockMatches || !tableMatches) {
      throw new Error("Workflow contract drift detected; regenerate the lock and table");
    }
    return { status: "current", contracts: contracts.length };
  }
  await Promise.all([
    writeFile(LOCK_FILE, lock, "utf8"),
    writeFile(TABLE_FILE, table, "utf8"),
  ]);
  return { status: "updated", contracts: contracts.length };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.some((arg) => !["--check"].includes(arg))) {
    throw new Error("Usage: node miku-scm-workflow-contracts.mjs [--check]");
  }
  const result = await updateWorkflowContracts({ check: args.includes("--check") });
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}
