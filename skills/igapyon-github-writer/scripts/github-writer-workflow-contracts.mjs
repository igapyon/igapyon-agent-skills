#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  WORKFLOW_CONTRACT_VERSION,
  WORKFLOW_DEFINITIONS,
} from "./github-writer-workflow-manifest.mjs";

export const WORKFLOW_CONTRACT_LOCK_VERSION = "github-writer.workflow-contract-lock/v2";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const skillRoot = path.dirname(scriptDirectory);
const lockFile = path.join(scriptDirectory, "github-writer-workflow-contract-lock.mjs");
const markdownFile = path.join(skillRoot, "references", "workflow-contracts.md");

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

export function canonicalText(value) {
  return String(value).replace(/\r\n?/g, "\n");
}

function sourceSetDigest(relativePaths, readText = readFileSync) {
  return sha256(relativePaths.map((relativePath) => (
    `${relativePath}\u0000${canonicalText(readText(path.join(skillRoot, relativePath), "utf8"))}`
  )).join("\u0000"));
}

export function buildContracts({ readText = readFileSync } = {}) {
  return WORKFLOW_DEFINITIONS.map((workflow) => {
    const runner = `scripts/${workflow.runner_entry}`;
    const runnerSources = [...workflow.contract_sources];
    const normativeSpec = `references/${workflow.references[0]}`;
    const contractTest = workflow.contract_test;
    const runnerSha256 = sourceSetDigest(runnerSources, readText);
    const normativeSpecSha256 = sourceSetDigest([normativeSpec], readText);
    const contractTestSha256 = sourceSetDigest([contractTest], readText);
    const pair = [
      workflow.id,
      String(WORKFLOW_CONTRACT_VERSION),
      runnerSha256,
      normativeSpecSha256,
      contractTestSha256,
    ].join("\n");
    return {
      id: workflow.id,
      contract_version: WORKFLOW_CONTRACT_VERSION,
      runner,
      runner_sources: runnerSources,
      normative_spec: normativeSpec,
      contract_test: contractTest,
      runner_sha256: runnerSha256,
      normative_spec_sha256: normativeSpecSha256,
      contract_test_sha256: contractTestSha256,
      contract_pair_sha256: sha256(pair),
    };
  });
}

function renderLock(contracts) {
  return `// Generated by github-writer-workflow-contracts.mjs. Do not edit.\n\n`
    + `export const WORKFLOW_CONTRACT_LOCK_VERSION = ${JSON.stringify(WORKFLOW_CONTRACT_LOCK_VERSION)};\n\n`
    + `export const WORKFLOW_CONTRACTS = Object.freeze(${JSON.stringify(contracts, null, 2)});\n\n`
    + "export function workflowContractById(id) {\n"
    + "  return WORKFLOW_CONTRACTS.find((entry) => entry.id === id) ?? null;\n"
    + "}\n";
}

function renderMarkdown(contracts) {
  const lines = [
    "# GitHub Writer Workflow Contracts",
    "",
    "Generated by `scripts/github-writer-workflow-contracts.mjs`. Do not edit by hand.",
    "",
    "| Workflow | Version | Runner | Contract sources | Normative spec | Contract test | Pair SHA-256 |",
    "| --- | ---: | --- | --- | --- | --- | --- |",
    ...contracts.map((entry) => (
      `| \`${entry.id}\` | ${entry.contract_version} | \`${entry.runner}\` | ${entry.runner_sources.map((source) => `\`${source}\``).join("<br>")} | \`${entry.normative_spec}\` | \`${entry.contract_test}\` | \`${entry.contract_pair_sha256}\` |`
    )),
    "",
  ];
  return lines.join("\n");
}

export function generate({ check = false, readText = readFileSync, writeText = writeFileSync } = {}) {
  const contracts = buildContracts({ readText });
  const outputs = [
    [lockFile, renderLock(contracts)],
    [markdownFile, renderMarkdown(contracts)],
  ];
  if (check) {
    const drift = outputs.filter(([file, expected]) => {
      try {
        return canonicalText(readText(file, "utf8")) !== expected;
      } catch {
        return true;
      }
    });
    if (drift.length > 0) {
      throw new Error(`Workflow contract drift: ${drift.map(([file]) => path.relative(skillRoot, file)).join(", ")}`);
    }
    return contracts;
  }
  for (const [file, content] of outputs) writeText(file, content, "utf8");
  return contracts;
}

function runCli(argv) {
  if (argv.length > 1 || (argv.length === 1 && argv[0] !== "--check")) {
    throw new Error("Usage: node github-writer-workflow-contracts.mjs [--check]");
  }
  const contracts = generate({ check: argv[0] === "--check" });
  process.stdout.write(`${argv[0] === "--check" ? "verified" : "generated"} ${contracts.length} workflow contracts\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    runCli(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
