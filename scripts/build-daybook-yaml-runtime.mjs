#!/usr/bin/env node

import fs from "node:fs";
import { builtinModules } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const projectRoot = fileURLToPath(new URL("..", import.meta.url));
const packagePath = path.join(projectRoot, "package.json");
const yamlPackagePath = path.join(projectRoot, "node_modules/yaml/package.json");
const yamlLicensePath = path.join(projectRoot, "node_modules/yaml/LICENSE");
const outputDirectory = path.join(
  projectRoot,
  "skills/igapyon-miku-daybook/assets/daybook/scripts/vendor",
);
const runtimePath = path.join(outputDirectory, "yaml-runtime.mjs");
const bundledLicensePath = path.join(outputDirectory, "yaml.LICENSE");
const GENERATED_YAML_VERSION = "2.9.1";

function fail(message) {
  throw new Error(message);
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

async function generatedFiles() {
  const rootPackage = readJson(packagePath);
  const yamlPackage = readJson(yamlPackagePath);
  const esbuildPackage = readJson(path.join(projectRoot, "node_modules/esbuild/package.json"));

  if (rootPackage.devDependencies?.yaml !== GENERATED_YAML_VERSION
    || yamlPackage.version !== GENERATED_YAML_VERSION) {
    fail(`Expected root development dependency yaml@${GENERATED_YAML_VERSION}`);
  }
  if (rootPackage.devDependencies?.esbuild !== esbuildPackage.version) {
    fail("esbuild must be exactly pinned in the root development dependencies");
  }
  if (yamlPackage.license !== "ISC") {
    fail(`Unexpected yaml license: ${yamlPackage.license ?? "(missing)"}`);
  }

  const result = await build({
    absWorkingDir: projectRoot,
    stdin: {
      contents: 'export { parse, stringify } from "./node_modules/yaml/dist/index.js";\n',
      resolveDir: projectRoot,
      sourcefile: "daybook-yaml-runtime-entry.mjs",
      loader: "js",
    },
    bundle: true,
    packages: "bundle",
    platform: "node",
    format: "esm",
    target: "node18",
    minify: false,
    sourcemap: false,
    legalComments: "none",
    write: false,
    metafile: true,
    // Keep the Node distribution's builtin requires as static ESM imports.
    plugins: [{
      name: "yaml-node-builtins",
      setup(pluginBuild) {
        pluginBuild.onResolve({ filter: /^(?:node:)?(?:buffer|process)$/ }, ({ path: specifier, namespace }) => {
          const builtin = specifier.replace(/^node:/, "");
          return namespace === "yaml-node-builtin"
            ? { path: `node:${builtin}`, external: true }
            : { path: builtin, namespace: "yaml-node-builtin" };
        });
        pluginBuild.onLoad({ filter: /.*/, namespace: "yaml-node-builtin" }, ({ path: builtin }) => ({
          contents: `import builtin from "node:${builtin}"; module.exports = builtin;`,
          loader: "js",
        }));
      },
    }],
  });

  const output = result.outputFiles[0];
  if (!output) fail("esbuild did not produce the YAML runtime module");
  const imports = Object.values(result.metafile.outputs).flatMap((entry) => entry.imports);
  const externalImports = imports.filter((entry) => entry.external);
  const nodeBuiltins = new Set(builtinModules.map((name) => name.replace(/^node:/, "")));
  const unsupportedImports = externalImports.filter((entry) => {
    const name = entry.path.replace(/^node:/, "");
    return !nodeBuiltins.has(name);
  });
  if (unsupportedImports.length) {
    fail(`YAML runtime has non-Node external imports: ${unsupportedImports.map((entry) => entry.path).join(", ")}`);
  }
  if (!result.metafile.inputs["node_modules/yaml/dist/index.js"]
    || Object.keys(result.metafile.inputs).some((input) => input.startsWith("node_modules/yaml/browser/"))) {
    fail("The generated runtime must include the pinned yaml Node.js distribution");
  }
  if (externalImports.some((entry) => entry.kind !== "import-statement")
    || /\b__require\s*\(\s*[^)\s]/.test(output.text)) {
    fail("Generated YAML runtime contains an unresolved dynamic require");
  }

  const banner = [
    "/*",
    " * Generated by: node scripts/build-daybook-yaml-runtime.mjs",
    ` * YAML source: yaml@${yamlPackage.version} Node.js distribution; esbuild@${esbuildPackage.version}`,
    " * yaml license: ISC; see yaml.LICENSE.",
    " * Do not edit this generated file directly.",
    " */",
  ].join("\n");
  return {
    [runtimePath]: `${banner}\n${output.text}`,
    [bundledLicensePath]: fs.readFileSync(yamlLicensePath, "utf8"),
  };
}

async function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.length === 1 && args[0] === "--check";
  if (args.length && !checkOnly) fail("Usage: node scripts/build-daybook-yaml-runtime.mjs [--check]");

  const outputs = await generatedFiles();
  const mismatches = [];
  for (const [filePath, expected] of Object.entries(outputs)) {
    if (checkOnly) {
      let actual;
      try { actual = fs.readFileSync(filePath, "utf8"); }
      catch { mismatches.push(path.relative(projectRoot, filePath)); continue; }
      if (actual !== expected) mismatches.push(path.relative(projectRoot, filePath));
    } else {
      fs.mkdirSync(path.dirname(filePath), { recursive: true });
      fs.writeFileSync(filePath, expected, "utf8");
    }
  }

  if (mismatches.length) {
    fail(`Generated YAML runtime is stale; run npm run build:daybook-yaml-runtime:\n${mismatches.join("\n")}`);
  }
  process.stdout.write(checkOnly
    ? "Daybook YAML runtime and license are current.\n"
    : "Generated daybook YAML runtime and license.\n");
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
